using System; // Подключение базовой библиотеки System для работы с консолью и генератором случайных чисел
namespace GuessNumberGame // Объявление пространства имен для нашей игры "Угадай число"
{ // Начало блока пространства имен GuessNumberGame
    class Program // Объявление основного класса игры
    { // Начало блока класса Program
        static void Main(string[] args) // Главная точка входа, откуда стартует выполнение программы
        { // Начало блока метода Main
            Console.OutputEncoding = System.Text.Encoding.UTF8; // Настройка вывода консоли в кодировку UTF-8 для правильного отображения русского текста
            Console.InputEncoding = System.Text.Encoding.UTF8; // Настройка ввода консоли в кодировку UTF-8 для корректного чтения с клавиатуры
            Console.WriteLine("=== Игра «Угадай число» ==="); // Вывод названия игры в консоль
            Console.WriteLine("Компьютер загадал число от 1 до 100. Попробуйте его отгадать!"); // Вывод правил игры для пользователя
            Random random = new Random(); // Создание объекта генератора псевдослучайных чисел
            int targetNumber = random.Next(1, 101); // Генерация случайного целого числа в диапазоне от 1 до 100 включительно
            int attemptsCount = 0; // Переменная-счетчик для подсчета количества совершенных попыток
            bool isGuessed = false; // Логический флаг, показывающий, отгадано ли число
            while (!isGuessed) // Цикл продолжается до тех пор, пока число не будет угадано (флаг isGuessed равен false)
            { // Начало тела игрового цикла
                Console.Write("Введите число: "); // Вывод приглашения ко вводу очередного варианта числа
                string input = Console.ReadLine(); // Чтение введенной пользователем строки из консоли
                int userNumber = Convert.ToInt32(input); // Преобразование введенной строки в целое число типа int
                attemptsCount++; // Увеличение счетчика попыток на единицу
                if (userNumber < targetNumber) // Проверка: если введенное число меньше загаданного
                { // Начало блока для случая, когда число меньше
                    Console.WriteLine("Больше!"); // Подсказка пользователю: загаданное число больше введенного
                } // Конец блока для случая, когда число меньше
                else if (userNumber > targetNumber) // Проверка: если введенное число больше загаданного
                { // Начало блока для случая, когда число больше
                    Console.WriteLine("Меньше!"); // Подсказка пользователю: загаданное число меньше введенного
                } // Конец блока для случая, когда число больше
                else // Ветка else срабатывает, когда введенное число в точности равно загаданному
                { // Начало блока победы
                    Console.WriteLine("Поздравляем! Вы угадали число " + targetNumber + " за " + attemptsCount + " попыток!"); // Вывод поздравления и числа попыток
                    isGuessed = true; // Установка флага в true для завершения игрового цикла while
                } // Конец блока победы
            } // Конец тела игрового цикла
            Console.WriteLine("Нажмите Enter для выхода..."); // Вывод подсказки о выходе из программы
            Console.ReadLine(); // Ожидание нажатия пользователем клавиши Enter перед закрытием консоли
        } // Конец блока метода Main
    } // Конец блока класса Program
} // Конец блока пространства имен
