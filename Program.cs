using System; // Подключение стандартной библиотеки System для ввода/вывода в консоль
using System.Globalization; // Подключение пространства имен Globalization для универсального чтения чисел с точкой и запятой
namespace CalculatorApp // Объявление пространства имен нашей программы
{ // Начало блока пространства имен
    class Program // Объявление основного класса программы
    { // Начало блока класса Program
        static void Main(string[] args) // Главная точка входа, с которой начинается выполнение программы
        { // Начало блока метода Main
            Console.OutputEncoding = System.Text.Encoding.UTF8; // Настройка кодировки вывода консоли на UTF-8 для корректного отображения русского текста
            Console.InputEncoding = System.Text.Encoding.UTF8; // Настройка кодировки ввода консоли на UTF-8
            Console.WriteLine("=== Калькулятор ==="); // Вывод заголовка программы на экран
            Console.Write("Введите первое число: "); // Вывод приглашения для ввода первого числа без перехода на новую строку
            string firstInput = Console.ReadLine(); // Считывание введенной строки с первого числа от пользователя
            double num1 = double.Parse(firstInput.Replace(',', '.'), CultureInfo.InvariantCulture); // Преобразование строки в число типа double с поддержкой точки и запятой
            Console.Write("Введите операцию (+, -, *, /): "); // Вывод приглашения для ввода знака операции
            char op = Console.ReadLine()[0]; // Считывание первого символа введенной строки в качестве знака операции
            Console.Write("Введите второе число: "); // Вывод приглашения для ввода второго числа
            string secondInput = Console.ReadLine(); // Считывание введенной строки со вторым числом от пользователя
            double num2 = double.Parse(secondInput.Replace(',', '.'), CultureInfo.InvariantCulture); // Преобразование строки во второе число типа double
            if (op == '+') // Проверка: если пользователь выбрал операцию сложения
            { // Начало блока обработки сложения
                double result = num1 + num2; // Сложение первого и второго числа и сохранение в переменную result
                Console.WriteLine("Результат: " + num1 + " + " + num2 + " = " + result); // Вывод результата сложения на экран
            } // Конец блока обработки сложения
            else if (op == '-') // Проверка: если пользователь выбрал операцию вычитания
            { // Начало блока обработки вычитания
                double result = num1 - num2; // Вычитание второго числа из первого и сохранение в переменную result
                Console.WriteLine("Результат: " + num1 + " - " + num2 + " = " + result); // Вывод результата вычитания на экран
            } // Конец блока обработки вычитания
            else if (op == '*') // Проверка: если пользователь выбрал операцию умножения
            { // Начало блока обработки умножения
                double result = num1 * num2; // Умножение первого числа на второе и сохранение в переменную result
                Console.WriteLine("Результат: " + num1 + " * " + num2 + " = " + result); // Вывод результата умножения на экран
            } // Конец блока обработки умножения
            else if (op == '/') // Проверка: если пользователь выбрал операцию деления
            { // Начало блока обработки деления
                if (num2 == 0) // Проверка деления на ноль через условный оператор if
                { // Начало блока обработки ошибки деления на ноль
                    Console.WriteLine("Ошибка: деление на ноль невозможно!"); // Вывод сообщения об ошибке при попытке деления на 0
                } // Конец блока обработки ошибки деления на ноль
                else // Ветка else, если второе число не равно нулю и делить можно
                { // Начало блока выполнения корректного деления
                    double result = num1 / num2; // Вычисление частного от деления первого числа на второе
                    Console.WriteLine("Результат: " + num1 + " / " + num2 + " = " + result); // Вывод результата деления на экран
                } // Конец блока выполнения деления
            } // Конец блока обработки деления
            else // Ветка else на случай, если введен неизвестный символ операции
            { // Начало блока обработки некорректной операции
                Console.WriteLine("Ошибка: некорректная операция '" + op + "'! Допустимы только +, -, *, /."); // Сообщение о неверной операции
            } // Конец блока обработки некорректной операции
            Console.WriteLine("Нажмите Enter для завершения программы..."); // Вывод подсказки о выходе из программы
            Console.ReadLine(); // Ожидание нажатия Enter пользователем перед закрытием консоли
        } // Конец блока метода Main
    } // Конец блока класса Program
} // Конец блока пространства имен
