using System; // Подключение стандартного пространства имен System для базовых типов и вывода в консоль
namespace PrimeNumbersApp // Объявление пространства имен для нашей программы поиска простых чисел
{ // Начало блока пространства имен PrimeNumbersApp
    class Program // Объявление класса программы
    { // Начало блока класса Program
        static void Main(string[] args) // Главный метод программы, точка входа при запуске
        { // Начало блока метода Main
            Console.OutputEncoding = System.Text.Encoding.UTF8; // Установка кодировки UTF-8 для корректного вывода русских букв
            Console.WriteLine("=== Программа для поиска простых чисел от 2 до 1000 ==="); // Вывод заголовка программы на экран
            int count = 0; // Инициализация счетчика найденных простых чисел
            for (int number = 2; number <= 1000; number++) // Внешний цикл перебора всех чисел в диапазоне от 2 до 1000
            { // Начало тела внешнего цикла
                bool isPrime = true; // Предполагаем по умолчанию, что текущее число number является простым
                for (int divisor = 2; divisor * divisor <= number; divisor++) // Внутренний цикл проверки делителей от 2 до квадратного корня из числа
                { // Начало тела внутреннего цикла
                    if (number % divisor == 0) // Проверка: если остаток от деления числа на делитель равен нулю
                    { // Начало блока при нахождении делителя
                        isPrime = false; // Число делится без остатка, следовательно, оно не простое
                        break; // Досрочно прерываем внутренний цикл проверки делителей
                    } // Конец блока проверки делителя
                } // Конец тела внутреннего цикла
                if (isPrime) // Проверка: если флаг остался true, значит число действительно простое
                { // Начало блока вывода простого числа
                    Console.Write(number + "\t"); // Вывод простого числа на экран с добавлением знака табуляции для ровных колонок
                    count++; // Увеличение общего счетчика найденных простых чисел на 1
                    if (count % 10 == 0) // Проверка: если в текущей строке уже выведено 10 чисел
                    { // Начало блока переноса строки
                        Console.WriteLine(); // Переход на новую строку для красивого и аккуратного отображения
                    } // Конец блока переноса строки
                } // Конец блока вывода простого числа
            } // Конец тела внешнего цикла
            Console.WriteLine(); // Дополнительный перенос строки после завершения вывода всех чисел
            Console.WriteLine("Всего простых чисел от 2 до 1000 найдено: " + count); // Вывод итогового количества найденных простых чисел
            Console.WriteLine("Нажмите Enter для выхода..."); // Вывод сообщения о завершении работы программы
            Console.ReadLine(); // Ожидание нажатия клавиши Enter перед закрытием консольного окна
        } // Конец блока метода Main
    } // Конец блока класса Program
} // Конец блока пространства имен
